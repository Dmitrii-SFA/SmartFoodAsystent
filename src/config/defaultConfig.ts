export function ensureProtectedLanguages(languages: LanguageOption[] = []): LanguageOption[] {
  const result: LanguageOption[] = Array.isArray(languages) ? [...languages] : [];

  // Guarantee that RU, EN, PL always exist intact, protected, with pristine canonical labels
  DEFAULT_INSTALLED_LANGUAGES.forEach((defaultLang) => {
    const existingIndex = result.findIndex(
      (l) => l.code.slice(0, 2).toLowerCase() === defaultLang.code.toLowerCase()
    );
    if (existingIndex === -1) {
      result.push({ ...defaultLang });
    } else {
      // Overwrite with canonical labels and name to fix any prior corrupted/unintended modifications
      result[existingIndex] = {
        ...defaultLang,
        isProtected: true,
      };
    }
  });

  return result;
}

