export function ensureProtectedMetrics(metrics: MetricConfig[] = []): MetricConfig[] {
  const result: MetricConfig[] = Array.isArray(metrics) ? [...metrics] : [];

  // Migration map for prior default colors to new required color scheme:
  // Proteins: #ef4444 -> #3b82f6 (blue)
  // Fats: #3b82f6 -> #eab308 (yellow)
  // Carbs: #10b981 -> #ef4444 (red)
  // Calories: #f59e0b -> #f97316 (orange)
  // Fiber: #8b5cf6 -> #22c55e (green)
  const legacyColorMigration: Record<string, { old: string[]; newColor: string }> = {
    proteins: { old: ['#ef4444', '#f87171', '#dc2626'], newColor: '#3b82f6' },
    fats: { old: ['#3b82f6', '#60a5fa', '#2563eb'], newColor: '#eab308' },
    carbs: { old: ['#10b981', '#34d399', '#059669'], newColor: '#ef4444' },
    calories: { old: ['#f59e0b', '#fbbf24', '#d97706'], newColor: '#f97316' },
    fiber: { old: ['#8b5cf6', '#a78bfa', '#7c3aed'], newColor: '#22c55e' },
  };

  // Guarantee that calories, proteins, fats, carbs, fiber, water always exist intact and cannot be removed
  PROTECTED_BASE_METRICS.forEach((baseMetric) => {
    const existingIndex = result.findIndex((m) => m.id === baseMetric.id);
    if (existingIndex === -1) {
      result.unshift({ ...baseMetric });
    } else {
      let currentColor = result[existingIndex].color || baseMetric.color;
      const mig = legacyColorMigration[baseMetric.id];
      if (mig && mig.old.includes(currentColor.toLowerCase())) {
        currentColor = mig.newColor;
      }
      const isCoreFour = ['calories', 'proteins', 'fats', 'carbs'].includes(baseMetric.id);
      const existingProductVis = result[existingIndex].showInProducts;
      result[existingIndex] = {
        ...baseMetric,
        ...result[existingIndex],
        color: currentColor,
        isProtected: true,
        // Crucial identifiers are locked
        id: baseMetric.id,
        unit: result[existingIndex].unit || baseMetric.unit,
        category: baseMetric.category,
        showInProducts: isCoreFour ? true : (existingProductVis !== undefined ? existingProductVis : baseMetric.showInProducts),
      };
    }
  });

  // Guarantee all built-in hidden nutrients are present in user config (hidden by default unless enabled by user)
  HIDDEN_DEFAULT_METRICS.forEach((hiddenMetric) => {
    const existingIndex = result.findIndex((m) => m.id === hiddenMetric.id);
    if (existingIndex === -1) {
      result.push({ ...hiddenMetric });
    } else {
      result[existingIndex] = {
        ...hiddenMetric,
        ...result[existingIndex],
        isProtected: true,
      };
    }
  });

  // Ensure all non-base metrics also have valid showInProducts defined
  return result.map((m) => {
    if (m.showInProducts === undefined) {
      return { ...m, showInProducts: false };
    }
    return m;
  });
}

export function ensureProtectedMealCategories(categories: MealCategoryConfig[] = []): MealCategoryConfig[] {
  const result: MealCategoryConfig[] = Array.isArray(categories) ? [...categories] : [];

  // Guarantee that breakfast, lunch, dinner, snack always exist intact and cannot be deleted
  PROTECTED_BASE_MEAL_CATEGORIES.forEach((baseCat) => {
    const existingIndex = result.findIndex((c) => c.id === baseCat.id);
    if (existingIndex === -1) {
      result.push({ ...baseCat });
    } else {
      // Lock protected status and keep original id & icon
      result[existingIndex] = {
        ...result[existingIndex],
        id: baseCat.id,
        isProtected: true,
      };
    }
  });

  return result;
}

export function ensureProtectedTheme(theme: any): any {
  const safeTheme = theme && typeof theme === 'object' ? { ...theme } : {};
  if (!PROTECTED_THEME_MODES.includes(safeTheme.mode)) {
    safeTheme.mode = 'dark';
  }
  return safeTheme;
}

export function ensureEntireConfigProtected(userConfig: UserConfig): UserConfig {
  const safeConfig: UserConfig = {
    ...userConfig,
    goalMode: userConfig.goalMode || 'maintain',
    installedLanguages: ensureProtectedLanguages(userConfig.installedLanguages),
    metrics: ensureProtectedMetrics(userConfig.metrics),
    mealCategories: ensureProtectedMealCategories(userConfig.mealCategories),
    theme: ensureProtectedTheme(userConfig.theme),
  };
  return safeConfig;
}

